-- Initial schema. Mirrors app/models.py; tests/test_schema.py checks the two still match.
-- Every row that belongs to a child carries child_id. Problems belong to no child.

-- ---------- who ----------

CREATE TABLE families (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE children (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    family_id    bigint NOT NULL REFERENCES families(id) ON DELETE CASCADE,
    first_name   text NOT NULL,
    grade        smallint,
    contest      text,
    focus        text,
    daily_goal   smallint NOT NULL DEFAULT 10,
    weekly_goal  smallint NOT NULL DEFAULT 50,
    placement    jsonb NOT NULL DEFAULT '{}',
    settings     jsonb NOT NULL DEFAULT '{}',
    created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_children_family_id ON children (family_id);

CREATE TABLE child_contests (
    child_id         bigint NOT NULL REFERENCES children(id) ON DELETE CASCADE,
    contest          text NOT NULL,
    last_year_score  numeric(6,1),
    last_year_max    numeric(6,1),
    note             text,
    PRIMARY KEY (child_id, contest)
);

CREATE TABLE custom_topics (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    family_id   bigint NOT NULL REFERENCES families(id) ON DELETE CASCADE,
    skill_id    text NOT NULL UNIQUE,
    name        text NOT NULL,
    topic       text NOT NULL,
    contests    jsonb NOT NULL DEFAULT '[]',
    note        text,
    created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_custom_topics_family_id ON custom_topics (family_id);

-- ---------- problems and answers ----------

CREATE TABLE problems (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill             text NOT NULL,
    level             smallint NOT NULL,
    contest           text,
    grade             smallint,
    source            text NOT NULL DEFAULT 'generated',
    source_year       smallint,
    source_number     smallint,
    answer_kind       text NOT NULL DEFAULT 'choice',
    question          text NOT NULL,
    choices           jsonb,
    answer_index      smallint,
    accepted_answers  jsonb,
    solution          text,
    hints             jsonb NOT NULL DEFAULT '[]',
    figure            jsonb,
    choice_figures    jsonb,
    figure_image      text,
    points            smallint,
    written_by        text,
    check_status      text NOT NULL DEFAULT 'unchecked',
    status            text NOT NULL DEFAULT 'draft',
    created_at        timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT source_valid       CHECK (source IN ('generated', 'past_paper')),
    CONSTRAINT answer_kind_valid  CHECK (answer_kind IN ('choice', 'typed')),
    CONSTRAINT check_status_valid CHECK (check_status IN ('unchecked', 'passed', 'failed')),
    CONSTRAINT status_valid       CHECK (status IN ('draft', 'verified', 'rejected', 'retired'))
);
CREATE INDEX problems_pick ON problems (skill, level, status);

CREATE TABLE problem_checks (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    problem_id    bigint NOT NULL REFERENCES problems(id) ON DELETE CASCADE,
    "check"       text NOT NULL,
    model         text,
    verdict       text NOT NULL,
    answer_given  text,
    ran_at        timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_problem_checks_problem_id ON problem_checks (problem_id);

CREATE TABLE problem_flags (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    problem_id   bigint NOT NULL REFERENCES problems(id) ON DELETE CASCADE,
    child_id     bigint REFERENCES children(id) ON DELETE SET NULL,
    raised_by    text NOT NULL,
    reason       text,
    resolution   text,
    resolved_at  timestamptz,
    created_at   timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT raised_by_valid  CHECK (raised_by IN ('child', 'pattern', 'reviewer', 'parent')),
    CONSTRAINT resolution_valid CHECK (resolution IS NULL OR resolution IN ('bad_problem', 'fine'))
);
CREATE INDEX ix_problem_flags_problem_id ON problem_flags (problem_id);

CREATE TABLE practice_sessions (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    child_id            bigint NOT NULL REFERENCES children(id) ON DELETE CASCADE,
    kind                text NOT NULL,
    focus               text,
    goal                smallint,
    position            smallint NOT NULL DEFAULT 0,
    planned             jsonb NOT NULL DEFAULT '[]',
    current_problem_id  bigint REFERENCES problems(id) ON DELETE SET NULL,
    status              text NOT NULL DEFAULT 'open',
    started_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT kind_valid   CHECK (kind IN ('placement', 'daily', 'topic')),
    CONSTRAINT status_valid CHECK (status IN ('open', 'done'))
);
CREATE INDEX practice_open ON practice_sessions (child_id, status);

CREATE TABLE mock_tests (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    child_id      bigint NOT NULL REFERENCES children(id) ON DELETE CASCADE,
    contest       text NOT NULL,
    grade         smallint,
    size          text NOT NULL DEFAULT 'full',
    status        text NOT NULL DEFAULT 'preparing',
    minutes       smallint,
    unit          text NOT NULL DEFAULT 'point',
    started_at    timestamptz,
    ends_at       timestamptz,
    last_seen_at  timestamptz,
    finished_at   timestamptz,
    questions     smallint,
    correct       smallint,
    score         numeric(6,1),
    max_score     numeric(6,1),
    seconds_used  integer,
    CONSTRAINT status_valid CHECK (status IN ('preparing', 'in_progress', 'finished', 'abandoned'))
);
CREATE INDEX ix_mock_tests_child_id ON mock_tests (child_id);

CREATE TABLE mock_test_items (
    mock_test_id  bigint NOT NULL REFERENCES mock_tests(id) ON DELETE CASCADE,
    position      smallint NOT NULL,
    problem_id    bigint NOT NULL REFERENCES problems(id),
    points        numeric(4,1) NOT NULL,
    label         text,
    PRIMARY KEY (mock_test_id, position)
);

CREATE TABLE answers (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    child_id             bigint NOT NULL REFERENCES children(id) ON DELETE CASCADE,
    problem_id           bigint NOT NULL REFERENCES problems(id),
    mode                 text NOT NULL,
    level                smallint NOT NULL,
    practice_session_id  bigint REFERENCES practice_sessions(id) ON DELETE SET NULL,
    mock_test_id         bigint REFERENCES mock_tests(id) ON DELETE CASCADE,
    chosen_index         smallint,
    typed_answer         text,
    correct              boolean NOT NULL,
    trouble_reason       text,
    note                 text,
    hints_used           smallint NOT NULL DEFAULT 0,
    seconds              integer,
    retries              smallint NOT NULL DEFAULT 0,
    fixed_on_retry       boolean NOT NULL DEFAULT false,
    points               smallint NOT NULL DEFAULT 0,
    answered_at          timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT mode_valid CHECK (mode IN ('placement', 'practice', 'retry', 'mock'))
);
CREATE INDEX answers_by_child ON answers (child_id, answered_at);
CREATE INDEX answers_seen ON answers (child_id, problem_id);

CREATE TABLE skill_progress (
    child_id    bigint NOT NULL REFERENCES children(id) ON DELETE CASCADE,
    skill       text NOT NULL,
    level       smallint NOT NULL DEFAULT 3,
    up          smallint NOT NULL DEFAULT 0,
    down        smallint NOT NULL DEFAULT 0,
    attempts    integer NOT NULL DEFAULT 0,
    correct     integer NOT NULL DEFAULT 0,
    reasons     jsonb NOT NULL DEFAULT '{}',
    recent      jsonb NOT NULL DEFAULT '[]',
    updated_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (child_id, skill)
);

-- ---------- agents ----------

CREATE TABLE tutor_messages (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    child_id    bigint NOT NULL REFERENCES children(id) ON DELETE CASCADE,
    problem_id  bigint REFERENCES problems(id) ON DELETE SET NULL,
    role        text NOT NULL,
    text        text NOT NULL,
    sent_at     timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT role_valid CHECK (role IN ('child', 'tutor'))
);
CREATE INDEX ix_tutor_messages_child_id ON tutor_messages (child_id);

CREATE TABLE agent_runs (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent       text NOT NULL,
    provider    text NOT NULL,
    model       text NOT NULL,
    child_id    bigint REFERENCES children(id) ON DELETE SET NULL,
    tokens_in   integer,
    tokens_out  integer,
    seconds     numeric(8,2),
    ok          boolean NOT NULL,
    error       text,
    ran_at      timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_agent_runs_agent ON agent_runs (agent);

CREATE TABLE reports (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    child_id    bigint REFERENCES children(id) ON DELETE CASCADE,
    kind        text NOT NULL,
    week_start  date NOT NULL,
    body        text NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT kind_valid CHECK (kind IN ('weekly_summary', 'review_findings'))
);
